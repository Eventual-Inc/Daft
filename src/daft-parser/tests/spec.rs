fn test_accepted(#[case] sql: &str) {
    let stmt = daft_parser::parse(sql).unwrap();
    assert_eq!(
        daft_parser::parse(&stmt.to_string()).unwrap(),
        stmt,
        "{stmt}"
    );
}

